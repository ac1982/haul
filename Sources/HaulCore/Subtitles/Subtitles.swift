        // zh-hans → zh-Hans
        if let m = key.firstMatch(of: /-[a-z]/) {
            key = key.replacingOccurrences(of: String(m.output), with: String(m.output).uppercased())
        }
        return languageTable[key] ?? ("und", "Undetermined")
    }

