    // MARK: saving

    public static func save(_ sub: SubtitleInfo, http: HTTPClient = .shared, session: Session) async throws {
        let body = try await http.getString(sub.url, session: session)
        let text = sub.path.hasSuffix(".srt") ? try srt(fromJSON: body) : body
        try text.write(toFile: sub.path, atomically: true, encoding: .utf8)
    }

    static func srt(fromJSON text: String) throws -> String {
        let json = try JSON.parse(text)
        if json.has("events") { return YtDlp.srt(fromJSON3: json) }
        var out = ""
        for (i, line) in json["body"].array.enumerated() {
            out += "\(i + 1)\n"
            let from = line["from"].double ?? 0
            let to = line["to"].double ?? 0
            out += "\(srtTime(from)) --> \(srtTime(to))\n"
            if line.has("content") { out += line["content"].stringValue + "\n" }
            out += "\n"
        }
        return out
    }

    /// `hh:mm:ss,fff`
    static func srtTime(_ seconds: Double) -> String {
        let total = Int(seconds)
        let ms = Int((seconds - Double(total)) * 1000 + 0.5)
        return String(format: "%02d:%02d:%02d,%03d", total / 3600, (total % 3600) / 60, total % 60, ms)
    }
